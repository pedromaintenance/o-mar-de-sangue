/* Council of Three Banners: gameplay, atlases, saves and exclusive oaths. */
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const read=p=>fs.readFileSync(p,'utf8');
const factionSource=read('SeaFactions.js');
const ctx={};vm.createContext(ctx);
vm.runInContext(factionSource+';this.F=SEA_FACTIONS;',ctx);
const F=ctx.F;
const ids=F.ids,probe=id=>({faction:F.initial(),alignment:{sobreviventes:0,corte:0,culto:0},sorties:0,levels:{casco:5,velas:5,canhoes:5}});
assert.equal(ids.length,3);
const all=[];
for(const id of ids){
 const d=F.definitions[id];
 assert(fs.existsSync(d.atlas),'Faction atlas not found: '+id);
 const b=fs.readFileSync(d.atlas);
 assert.equal(b.readUInt32BE(16),1460,id+' atlas width');
 assert.equal(b.readUInt32BE(20),1560,id+' atlas height');
 assert.equal(F.preview(id,1).includes('nivel_01.png'),true);
 assert.equal(F.preview(id,20).includes('nivel_20.png'),true);
 assert(fs.existsSync(F.preview(id,1)),id+' frame 1 missing');
 assert(fs.existsSync(F.preview(id,20)),id+' frame 20 missing');
 const p=probe(id),orig=JSON.stringify(p.levels);
 assert(!F.status(p,id).ok,'no reputation, no entry');
 p.alignment[id]=40;
 assert(!F.status(p,id).ok,'score never replaces the oath trial');
 const trial={sobreviventes:'refugees_1',corte:'parley_2',culto:'daegon_3'}[id];
 const scene={faction:p.faction};
 assert(F.recordChoice(scene,{id:trial}));
 p.faction=scene.faction;
 assert(F.status(p,id).ok,'proof and reputation open the oath');
 assert(F.join(p,id).ok);
 assert.equal(F.faction(p),id);
 assert.equal(F.texture(p),d.ship);
 assert.equal(JSON.stringify(p.levels),orig,'joining must preserve all upgrades');
 assert(!F.join(p,ids.find(x=>x!==id)).ok,'oaths must be exclusive');
 const previous=p.alignment[id];
 assert(F.leave(p).ok);
 assert.equal(p.faction.allegiance,null);
 assert.equal(p.alignment[id],previous-20);
 assert.equal(JSON.stringify(p.levels),orig,'desertion must not remove upgrades');
 p.alignment[ids.find(x=>x!==id)]=80;
 const other=ids.find(x=>x!==id);
 p.faction.proofs[other]=true;
 assert(!F.status(p,other).ok,'desertion imposes one independent sortie');
 p.sorties++;
 assert(F.status(p,other).ok);
 assert(F.join(p,other).ok);
 assert.equal(p.faction.history.length,3);
 all.push(id);
}
const rescued={faction:F.initial()};
assert(!F.recordContract(rescued,{id:'rescue',completed:false}));
assert(F.recordContract(rescued,{id:'rescue',completed:true}));
assert.equal(rescued.faction.proofs.sobreviventes,true);
assert(!F.recordContract(rescued,{id:'rescue',completed:true}),'no duplicate proof');
assert.equal(F.texture({faction:F.initial()}),'player-ship-stages');
assert(F.status({alignment:{sobreviventes:100},faction:F.initial(),sorties:0},'sobreviventes').ok===false);
const game=read('Game.js'),islands=read('SeaIslands.js'),menu=read('SeaMenus.js'),port=read('PortUI.js'),sw=read('sw.js'),html=read('index.html'),transfer=read('SeaSaveTransfer.js');
for(const [file,source] of [['Game.js',game],['SeaFactions.js',factionSource],['SeaIslands.js',islands],['SeaMenus.js',menu],['PortUI.js',port],['SeaSaveTransfer.js',transfer]])new vm.Script(source,{filename:file});
assert(html.includes('<script src="SeaFactions.js"></script>'));
assert(game.includes('SEA_FACTIONS.texture(this.profile)'));
assert(game.includes('SEA_FACTIONS.recordContract(this,this.contract)'));
assert(game.includes('faction:this.faction'));
assert(islands.includes('SEA_FACTIONS.recordChoice(s,choice)'));
assert(menu.includes('SEA_FACTIONS.texture(scene.profile||SeaProfile.load())'));
assert(port.includes("data-action=\"faction:"));
assert(port.includes('CONSELHO DAS TRÊS BANDEIRAS'));
assert(port.includes("page==='council'?this.council(p):"));
assert(transfer.includes("withFaction=[...withAlignment,'faction']"));
for(const id of ids){
 assert(sw.includes(F.definitions[id].atlas),id+' must be cached offline');
 assert(game.includes('this.load.spritesheet(def.ship,def.atlas'),id+' must be loaded in Phaser');
}
assert(sw.includes('./SeaFactions.js'));
assert(sw.includes('v100-three-banners-factions'));
console.log('PASS factions: '+all.join(', ')+'; 20 frames each, proof/reputation/jurament/desertion, scene, menu and PWA');
